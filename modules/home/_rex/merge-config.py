#!/usr/bin/env python3
"""Keep local Lua intact while updating the Nix-owned loader."""

import argparse
import os
from pathlib import Path
import shutil
import subprocess
import tempfile

BEGIN = "-- BEGIN dotfiles Rex configuration\n"
END = "-- END dotfiles Rex configuration\n"


def merge(original, managed):
    block = BEGIN + f'dofile({managed!r})\n' + END
    if BEGIN not in original and END not in original:
        return block + original
    if original.count(BEGIN) != 1 or original.count(END) != 1:
        raise ValueError("ambiguous Rex configuration markers; leaving file unchanged")
    start = original.index(BEGIN)
    end = original.index(END)
    if end < start:
        raise ValueError("reversed Rex configuration markers; leaving file unchanged")
    return original[:start] + block + original[end + len(END):]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("init", type=Path)
    parser.add_argument("managed", type=Path)
    parser.add_argument("rex")
    args = parser.parse_args()
    # Activation can itself run inside a remote Rex terminal. Always operate
    # on this account's local server, not the inherited remote target.
    os.environ.pop("REX_SERVER", None)
    path = args.init
    path.parent.mkdir(parents=True, exist_ok=True)
    original = path.read_text() if path.exists() else ""
    # Lua string quoting: these paths are generated by Nix, not arbitrary Lua.
    managed = str(args.managed)
    if any(c in managed for c in "'\\\n\r"):
        raise ValueError("unsupported character in managed Lua path")
    updated = merge(original, managed)
    fd, candidate = tempfile.mkstemp(prefix=".init-", suffix=".lua", dir=path.parent)
    try:
        with os.fdopen(fd, "w") as stream:
            stream.write(updated)
        # Validation happens even when the loader is unchanged: its fragment may
        # have changed in this generation. A failure never replaces local Lua.
        subprocess.run([args.rex, "config", "check", candidate], check=True)
        if updated != original:
            if path.exists():
                backup_fd, backup = tempfile.mkstemp(prefix="init.lua.backup-", dir=path.parent)
                os.close(backup_fd)
                shutil.copyfile(path, backup)
            os.replace(candidate, path)
        # Do not start an extra server during activation, especially on macOS.
        status = subprocess.run([args.rex, "--autostart=false", "server", "status"], capture_output=True)
        if status.returncode == 0:
            subprocess.run([args.rex, "config", "reload"], check=True)
    finally:
        Path(candidate).unlink(missing_ok=True)


if __name__ == "__main__":
    main()
